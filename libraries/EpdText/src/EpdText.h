// Glyph lookup: pointer to the 5 column bytes, or NULL when out of range.
// Blank slots return their (zero) row — the renderer draws nothing for them.
static inline const uint8_t *epdtGlyph(char c) {
  unsigned char u = (unsigned char)c;
  if (u < EPDT_FIRST || u >= EPDT_FIRST + EPDT_COUNT) return NULL;
  return EPDT_FONT[u - EPDT_FIRST];
}

// Pixel width of `len` chars at `scale` with `track` px tracking.
static inline int epdtTextWidth(int len, int scale, int track) {
  if (len <= 0) return 0;
  return len * (EPDT_GLYPH_W * scale + track) - track;
}

